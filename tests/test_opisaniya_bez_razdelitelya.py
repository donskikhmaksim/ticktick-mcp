"""Ворота 1 (пункт 1.1.8, docs/TZ/inventar_opisaniy.md, расхождение #16 у
`manual_triage`) — докстринги команд не должны цитировать заменитель
«(без названия ...)» через точку-разделитель (U+00B7, «·»).

ПОЧЕМУ ИМЕННО ЭТОТ СИМВОЛ И ИМЕННО В ЭТОМ КОНТЕКСТЕ. Компактная строка
задачи (`format_task_line`, server.py) уже использует «·» как разделитель
МЕЖДУ мета-полями («📎 1 файл · due 2026-08-09»). Если бы заменитель
безымянной задачи ТОЖЕ нёс «·» внутри себя («(без названия · 📎 1 файл)»),
то у задачи без названия рядом с любым другим мета-полем «·» встретился бы
ДВАЖДЫ в одной строке — и текст стал бы неразличим: где заканчивается
заменитель и где начинается следующее поле. Поэтому производящий код
(`_untitled_label`, server.py:594-620) печатает заменитель через ДВОЕТОЧИЕ:
«(без названия: 📎 1 файл)». Инвентаризация 1.1.7 (docs/TZ/inventar_opisaniy.md)
нашла, что докстринг `manual_triage` (и приватный хелпер `_triage_untitled_claim`
рядом) цитировал устаревший пример с точкой — модель, скопировавшая его
дословно, получила бы текст, не совпадающий с тем, что реально сравнивает
`_is_untitled_placeholder`.

ПОЧЕМУ ПРОВЕРКА ЧЕРЕЗ РЕЕСТР, А НЕ ГРЕП ПО ФАЙЛУ. `server.mcp.list_tools()` —
тот же путь, которым сервер реально отвечает на `tools/list`; `t.description`
там — это докстринг функции как он есть, включая любой символ внутри. Тест
обходит ВСЕ зарегистрированные `@mcp.tool()` команды разом, так что ловит и
`manual_triage`, и любой будущий регресс в ЛЮБОЙ другой команде, куда пример
мог бы скопироваться.
"""
import asyncio
import re

import pytest

from ticktick_mcp.src import server

# U+00B7 MIDDLE DOT — разделитель мета-полей в компактной строке задачи.
# Внутри заменителя «без названия» он запрещён — там обязано быть двоеточие.
_MIDDLE_DOT = "·"

# «без названия», за которым (не пересекая двоеточие и не уходя на другую
# строку) в пределах короткого хвоста встречается «·» — это ровно форма
# устаревшего примера «(без названия · 📎 1 файл)».
_BAD_PLACEHOLDER_RE = re.compile(r"без названия[^\n:]{0,12}" + _MIDDLE_DOT)


def _registered_tools():
    return asyncio.run(server.mcp.list_tools())


def test_no_middle_dot_inside_untitled_placeholder_in_any_tool_docstring():
    tools = _registered_tools()
    assert tools, "реестр команд пуст — обход не сработал"

    offenders = []
    for t in tools:
        desc = t.description or ""
        m = _BAD_PLACEHOLDER_RE.search(desc)
        if m:
            offenders.append((t.name, m.group(0)))

    assert not offenders, (
        "в описании этих команд заменитель «без названия» использует "
        f"запрещённую точку-разделитель «{_MIDDLE_DOT}» вместо двоеточия "
        f"(конфликтует с «·» как разделителем мета-полей в компактной "
        f"строке задачи, format_task_line): "
        f"{[(name, frag) for name, frag in offenders]}"
    )


if __name__ == "__main__":
    import sys
    sys.exit(pytest.main([__file__, "-v"]))
